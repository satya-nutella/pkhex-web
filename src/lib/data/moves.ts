/**
 * Get base PP for a move.
 */
export function getBasePP(moveId: number): number {
  if (moveId < 0 || moveId >= MOVE_PP_1.length) {
    return 0;
  }
  return MOVE_PP_1[moveId];
}

/**
 * Check if a move ID is valid (exists).
 */
export function isValidMove(moveId: number): boolean {
  return moveId > 0 && moveId < MOVES_EN.length;
}

/**
 * Get maximum move ID for a generation.
 */
export function getMaxMoveId(generation: number): number {
  switch (generation) {
    case 1:
      return MAX_MOVE_ID_1;
    case 2:
      return MAX_MOVE_ID_2;
    case 3:
      return MAX_MOVE_ID_3;
    default:
      return MAX_MOVE_ID_3;
  }
}
