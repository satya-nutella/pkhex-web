/**
 * Get base stats for a Pokemon
 */
export function getBaseStats(
  species: number,
  generation: number = 1,
): BaseStats {
  const stats = BASE_STATS_GEN1[species] || [0, 0, 0, 0, 0, 0];
  return {
    hp: stats[0],
    atk: stats[1],
    def: stats[2],
    spe: stats[3],
    spa: stats[4],
    spd: stats[5],
  };
}

/**
 * Get base stat total
 */
export function getBaseStatTotal(
  species: number,
  generation: number = 1,
): number {
  const stats = getBaseStats(species, generation);
  return stats.hp + stats.atk + stats.def + stats.spe + stats.spa + stats.spd;
}
